def process_query(trajectory, processed_instance_id, output_path):
    instance_id = trajectory['instance_id']
    # print(instance_id)
    patch = trajectory['patch']
    tool_sequence = trajectory['tool_sequence']
    reward = trajectory['reward']
    scores = trajectory['scores']

    if instance_id in processed_instance_id: return 
    # if instance_id != '151.context': return
    # print(instance_id)
   #  user_requirement_origen = trajectory['user_requirement']
   #  print(user_requirement_origen)
    user_requirement = ""
    query = trajectory['query']
    func_list = json.loads(query['func_list'])
    for idx, func in enumerate(func_list):
      #   print(func)
        user_requirement += f'[功能点 {idx + 1}]: {func["name"]}\n'
        user_requirement += f'要求: {func["requirement"]}\n'
        user_requirement += f'LLM Patch打分: {scores[idx]}\n\n'
    

    user_prompt = ""
    user_prompt += f"[User Requirement]:\n{user_requirement}\n"
    user_prompt += f"[LLM Patch]:\n{patch}\n"
    user_prompt += f"[Patch Feature Scores]:\n{scores}\n"
    user_prompt += f"[Patch Average Scores]:\n{reward}\n"
    user_prompt += f"[LLM Tool Sequence]:\n{tool_sequence}\n"
   #  print(user_prompt)

    messages = [
        {'role': 'system', 'content': system_prompt},
        {'role': 'user', 'content': user_prompt}
    ]
    response = get_response(messages)
    # print(response)
    parsed_response = parse_response(response)
   #  print(parsed_response)

    result = {}
    for key, value in trajectory.items(): result[key] = value
    for key, value in parsed_response.items(): result[key] = value

    json_str = json.dumps(result, ensure_ascii = False)
    with open(output_path, 'a', encoding='utf-8') as f: f.write(json_str + '\n')
    print(f"Processed trajectory:  {instance_id}")


def process_query_wrapped(args):
    trajectory, processed_instance_id, output_path = args
    try:
        process_query(trajectory, processed_instance_id, output_path)
    except Exception as e:
        print(f"ERROR: {e}")

def main(trajectory_path: str, output_folder: str, max_workers: int = 10):
    if not os.path.exists(output_folder): os.makedirs(output_folder)
    output_path = f'{output_folder}/deepseek_trajectory_analysis.jsonl'

    if not os.path.exists(output_path):
        with open(output_path, 'w') as f: f.write("")
        processed_instance_id = []
    else:
        processed_results = read_jsonl(output_path)
        processed_instance_id = [result['instance_id'] for result in processed_results]
    
    # Case Study
    # processed_instance_id = []

    max_workers = max_workers
    trajectorys = read_jsonl(trajectory_path)
    task_args = [(trajectory, processed_instance_id, output_path) for trajectory in trajectorys]
    with ThreadPoolExecutor(max_workers = max_workers) as executor: 
        executor.map(process_query_wrapped, task_args)

